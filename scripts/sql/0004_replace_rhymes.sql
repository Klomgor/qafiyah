SELECT setval(pg_get_serial_sequence('rhymes', 'id'),
              (SELECT max(id) FROM rhymes));

-- Recreate the stats view with the new shape. `pattern` becomes `name`.
CREATE VIEW rhyme_stats AS
SELECT
  r.id                                          AS id,
  r.letter                                      AS letter,
  r.slug                                        AS slug,
  r.name                                        AS name,
  count(p.id)::int                              AS poems_count,
  count(DISTINCT p.poet_id)::int                AS poets_count
FROM rhymes r
LEFT JOIN poems p ON p.rhyme_id = r.id
GROUP BY r.id, r.letter, r.slug, r.name;

-- Post-flight: must have exactly 36 letter rows.
DO $$
DECLARE
  v_count integer;
BEGIN
  SELECT count(*) INTO v_count FROM rhymes;
  IF v_count <> 36 THEN
    RAISE EXCEPTION 'post-flight failed: expected 36 rhyme rows, found %', v_count;
  END IF;
END $$;

