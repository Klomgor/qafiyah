-- scripts/sql/0004_replace_rhymes.sql
-- One-shot migration applied to the 0014 dump to produce the 0015 baseline.
-- Operations (single transaction):
--   1. Pre-flight: assert the legacy 32-pattern rhymes layout is present.
--   2. DROP the rhyme_stats view (depends on rhymes.pattern).
--   3. UPDATE poems SET rhyme_id = NULL (about to lose the referent).
--   4. DROP and recreate the rhymes table with (id, letter, slug, name).
--   5. INSERT the 36 canonical qafiyah-letter rows with deterministic ids.
--   6. setval the identity sequence to 36.
--   7. CREATE VIEW rhyme_stats with the new column shape.
--
-- A separate Bun script (scripts/extract-rhymes.ts) repopulates
-- poems.rhyme_id from poems.content after this file runs.
--
-- NOT idempotent: re-running on already-migrated data raises an exception
-- via the pre-flight guard below.
BEGIN;

DO $$
DECLARE
  v_legacy_count integer;
  v_has_pattern  integer;
BEGIN
  -- Pre-flight: legacy layout has 32 rows and a `pattern` column.
  SELECT count(*) INTO v_has_pattern
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name = 'rhymes' AND column_name = 'pattern';
  IF v_has_pattern <> 1 THEN
    RAISE EXCEPTION 'pre-flight failed: rhymes.pattern column not found (already migrated?)';
  END IF;

  SELECT count(*) INTO v_legacy_count FROM rhymes;
  IF v_legacy_count <> 32 THEN
    RAISE EXCEPTION 'pre-flight failed: expected 32 legacy rhyme rows, found %', v_legacy_count;
  END IF;
END $$;

-- Drop the stats view first; it selects rhymes.pattern.
DROP VIEW IF EXISTS rhyme_stats;

-- Drop FK values; the script that re-derives them runs after this file.
UPDATE poems SET rhyme_id = NULL;

-- Replace the table entirely. CASCADE drops the FK from poems.rhyme_id,
-- which we re-add below.
DROP TABLE rhymes CASCADE;

CREATE TABLE rhymes (
  id     smallint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  letter text     NOT NULL UNIQUE,
  slug   text     NOT NULL UNIQUE,
  name   text     NOT NULL
);

-- Re-add the FK that CASCADE dropped.
ALTER TABLE poems
  ADD CONSTRAINT poems_rhyme_id_fkey
  FOREIGN KEY (rhyme_id) REFERENCES rhymes(id);

